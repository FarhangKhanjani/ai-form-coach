// Writes docs/exercises/<id>.md for every catalog exercise from the technique dataset and the app's checks.
// Run: npx vite-node scripts/gen-exercise-docs.ts   (re-run after changing the catalog or the dataset)
import fs from "node:fs";
import path from "node:path";
import { CATALOG } from "../src/exercises/generic/catalog";

const ROOT = path.resolve(__dirname, "..");
const ds = JSON.parse(fs.readFileSync(path.join(ROOT, "docs/research/exercise_technique_dataset.json"), "utf8"));
const esc = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const VIEW: Record<string, string> = { front: "front", side: "side", diagonal: "diagonal" };

for (const d of CATALOG) {
  const ex = ds.exercises.find((e: { id: string }) => e.id === d.datasetId);
  const checked = new Set(d.checks.flatMap(c => c.source.checkpoints));
  const lines: string[] = [];
  lines.push(`# ${d.name} — form standard`, "");
  lines.push(`Version: v0 (draft, generated) · Coach review: not yet · Generated by \`scripts/gen-exercise-docs.ts\` from \`docs/research/exercise_technique_dataset.json\` (dataset v${ds.dataset_meta.version}, ${ds.dataset_meta.created}) and \`src/exercises/generic/catalog.ts\`.`, "");
  lines.push(`Equipment: ${d.equipment}. Mode: ${d.mode === "hold" ? `timed hold (target ${d.hold!.targetS} s; ${d.hold!.targetSource})` : "reps"}.`, "");
  lines.push("## Camera", "", `${d.filming}`, "", `Views: ${d.views.map(v => VIEW[v]).join(", ")} (default **${d.defaultView}**).`, "");
  if (d.signal) lines.push(`Rep detection: ${d.signal.label.toLowerCase()}; at rest it is ${d.signal.rest}; a rep starts past ${d.signal.enter}°, ends back past ${d.signal.exit}°, and only counts if it reaches ${d.signal.mustReach}°. [Placeholder] thresholds.`, "");

  lines.push("## What the app checks", "", "| Error | Views | Correct if | Dataset checkpoints | Where the limit comes from |", "|---|---|---|---|---|");
  for (const c of d.checks) {
    const lim = c.limit.min !== undefined ? `≥ ${c.limit.min} ${c.unit}` : `≤ ${c.limit.max} ${c.unit}`;
    lines.push(`| ${esc(c.name)} (\`${c.code}\`, ${c.severity}) | ${c.views.join(", ")} | ${esc(lim)} | ${c.source.checkpoints.join(", ")} | ${esc(c.source.limit)} |`);
  }
  lines.push("", "Cue spoken for each error: " + d.checks.map(c => `${c.name}: "${c.cue}"`).join("; ") + ".", "");

  lines.push("## Setup tips shown before starting (not checked by the camera)", "", ...d.tips.map(t => `- ${t}`), "");

  lines.push("## All checkpoints from the dataset", "", "✔ = checked by the app (see above). Agreement: consensus / single_source / conflict, as recorded in the dataset.", "",
    "| ID | Phase | Body part | Expected | Number | Agreement | Sources | App |", "|---|---|---|---|---|---|---|---|");
  for (const cp of ex.checkpoints) {
    const num = cp.numeric ? `${cp.numeric.value} ${cp.numeric.unit}${cp.numeric.note ? ` (${cp.numeric.note})` : ""}` : "";
    lines.push(`| ${cp.id} | ${cp.phase} | ${esc(cp.body_part)} | ${esc(cp.expected)} | ${esc(num)} | ${cp.agreement} | ${cp.source_ids.join(", ")} | ${checked.has(cp.id) ? "✔" : ""} |`);
  }
  lines.push("");
  const conflicts = ex.checkpoints.filter((c: { agreement: string }) => c.agreement === "conflict");
  if (conflicts.length) {
    lines.push("## Where sources disagree (for the coach to decide)", "");
    for (const c of conflicts) lines.push(`- **${c.id} ${c.parameter}:** ${Object.entries(c.per_source ?? {}).map(([k, v]) => `${k}: ${v}`).join("; ")}`);
    lines.push("");
  }
  if (ex.common_errors?.length) {
    lines.push("## Common errors named by the sources", "", "| Error | Do instead | Sources |", "|---|---|---|");
    for (const e of ex.common_errors) lines.push(`| ${esc(e.error)} | ${esc(e.correct_instead)} | ${e.source_ids.join(", ")} |`);
    lines.push("");
  }
  if (ex.not_specified_by_sources?.length) lines.push("## Not specified by any source", "", ...ex.not_specified_by_sources.map((s: string) => `- ${s}`), "");
  lines.push("## Limitations", "",
    "- Numbers come from coaching texts, not biomechanics measurements; most limits are [Placeholder] values to be set from labeled reps and a coach (docs/how-scoring-works.md).",
    "- Angles are 2D, from the side nearer the camera; they are only valid when the camera sees the movement from the stated view.",
    "- The pose model has no spine points: rounding or arching of the back can't be measured.",
    "- There is no bar keypoint; the hands stand in for the bar.", "");
  lines.push("## Sources", "", ...ex.sources.map((s: { id: string; name: string; url: string; read_depth: string }) => `- **${s.id}** — ${s.name}. ${s.url} (read: ${s.read_depth})`), "");
  fs.writeFileSync(path.join(ROOT, "docs/exercises", `${d.id}.md`), lines.join("\n"));
  console.log(`docs/exercises/${d.id}.md`);
}
